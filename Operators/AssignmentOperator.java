package Operators;

public class AssignmentOperator {
    public static void main(String[] args){
        int A = 10, B = 5;
        // A = A + 10;
        A += 10;
        System.out.println(A);  // 20
        // B = B - 5;
        B -= 5;
        System.out.println(B);  //  0
        // A = A * 10;
        A *= 10;
        System.out.println(A);  //  200
        // B = B / 5;
        B *= 5;
        System.out.println(B);  //   0

    }
    
}
