package Operators;

public class RelationalOPerator {
    public static void main(String[] args){
        // Relational Operator
        int A = 10;
        int B = 5;
        // Equal to
        System.out.println(A==B);
        //  Not Equal to
        System.out.println(A!= B);
        //  Is Greater Than
        System.out.println(A > B);
        // Is less than
        System.out.println(A<B);
        // Greater than equal to
        System.out.println(A >= B); 
        // Less than equal to
        System.out.println(A <= B);
    }
}
