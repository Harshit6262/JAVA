package Operators;

public class ArithmeticOperator {
    public static void main (String args []){
        int A = 10;
        int B = 5;
        System.out.println("Add :" + (A+B));                     // 15
        System.out.println("Substract :" + (A -B));              // 5 
        System.out.println("Multiply :" + (A*B));                // 50
        System.out.println("Divide :" + (A/B));                  // 2
        System.out.println("Modulo(remainder) :" + (A%B));       // 0
    }
}
